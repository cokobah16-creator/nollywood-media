"""
NACECA build script.

Pipeline:
  1. Concatenate all source modules in dependency order → src/_bundle.js
  2. Inline _bundle.js + styles.css into index.html → naceca.html (single-file build)

Dependency order matters because we use plain <script> globals (no ES modules).
This avoids requiring a webserver — naceca.html runs from any file:// URL.
"""

