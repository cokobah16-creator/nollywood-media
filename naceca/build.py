def build_bundle():
    parts = []
    parts.append(
        "/* =========================================================================\n"
        "   NACECA · src/_bundle.js  (auto-generated by build.py — do not edit)\n"
        "   Source modules under config/, systems/, scenes/ — edit those instead.\n"
        "   ========================================================================= */\n\n"
    )
    for rel in LOAD_ORDER:
        path = os.path.join(SRC, rel)
        if not os.path.exists(path):
            print(f"  ! missing {rel}")
            continue
        with open(path, "r", encoding="utf-8") as f:
            content = f.read()
        parts.append(f"\n/* ---------- {rel} ---------- */\n")
        parts.append(content)
        parts.append("\n")
    bundle = "".join(parts)
    with open(BUNDLE_OUT, "w", encoding="utf-8") as f:
        f.write(bundle)
    print(f"  bundle: {BUNDLE_OUT}  ({len(bundle):,} chars)")
    return bundle

def build_html(bundle):
    with open(HTML_IN, "r", encoding="utf-8") as f:
        html = f.read()
    with open(CSS_IN, "r", encoding="utf-8") as f:
        css = f.read()
    # Inline the CSS — replace the <link> with a <style> block
    html = re.sub(
        r'<link rel="stylesheet" href="styles\.css"\s*/?>',
        lambda m: f"<style>\n{css}\n</style>",
        html,
    )
    # Inline other local scripts (vendor loaders, generated art) as their own <script> blocks
    def _inline_local(m):
        p = os.path.join(ROOT, m.group(1))
        with open(p, "r", encoding="utf-8") as fh:
            return f"<script>\n{fh.read()}\n</script>"
    html = re.sub(r'<script src="(src/(?:vendor|assets)/[^"]+\.js)"></script>', _inline_local, html)
    # Inline the bundle — replace the <script src="src/_bundle.js"> with a <script>...</script>
    html = re.sub(
        r'<script src="src/_bundle\.js"></script>',
        lambda m: f"<script>\n{bundle}\n</script>",
        html,
    )
    # Append the v12 layer before </body>
    parts = []
    for name in V12_CSS:
        with open(os.path.join(V12_DIR, name), "r", encoding="utf-8") as fh:
            parts.append(f'<style id="{name[:-4]}">\n{fh.read()}\n</style>')
    for name in V12_JS:
        with open(os.path.join(V12_DIR, name), "r", encoding="utf-8") as fh:
            code = fh.read()
        if "</script" in code.lower():
            raise SystemExit(f"v12/{name} contains a closing script tag")
        parts.append(f"<script>/* ---------- {name} (v12) ---------- */\n{code}\n</script>")
    # Append the v13 layer after v12
    for name in V13_CSS:
        with open(os.path.join(V13_DIR, name), "r", encoding="utf-8") as fh:
            parts.append(f'<style id="{name[:-4]}">\n{fh.read()}\n</style>')
    for name in V13_JS:
        with open(os.path.join(V13_DIR, name), "r", encoding="utf-8") as fh:
            code = fh.read()
        if "</script" in code.lower():
            raise SystemExit(f"v13/{name} contains a closing script tag")
        parts.append(f"<script>/* ---------- {name} (v13) ---------- */\n{code}\n</script>")
    # Append the beta layer after v12
    for name in BETA_CSS:
        with open(os.path.join(BETA_DIR, name), "r", encoding="utf-8") as fh:
            parts.append(f'<style id="beta-{name[:-4]}">\n{fh.read()}\n</style>')
    for name in BETA_JS:
        with open(os.path.join(BETA_DIR, name), "r", encoding="utf-8") as fh:
            code = fh.read()
        if "</script" in code.lower():
            raise SystemExit(f"beta/{name} contains a closing script tag")
        parts.append(f"<script>/* ---------- beta/{name} ---------- */\n{code}\n</script>")
    # Append the tactics layer after the beta (missing files are skipped; each file is syntax-checked)
    for name in TACTICS_CSS:
        p = os.path.join(TACTICS_DIR, name)
        if not os.path.exists(p):
            continue
        with open(p, "r", encoding="utf-8") as fh:
            parts.append(f'<style id="tac-{name[:-4]}">\n{fh.read()}\n</style>')
    for name in TACTICS_JS:
        p = os.path.join(TACTICS_DIR, name)
        if not os.path.exists(p):
            print(f"  · tactics/{name} not present, skipped")
            continue
        with open(p, "r", encoding="utf-8") as fh:
            code = fh.read()
        if "</script" in code.lower():
            raise SystemExit(f"tactics/{name} contains a closing script tag")
        if os.system(f'node --check "{p}" 2>&1') != 0:
            raise SystemExit(f"tactics/{name} has syntax errors")
        parts.append(f"<script>/* ---------- tactics/{name} ---------- */\n{code}\n</script>")
    stamp_at = "<!--NACECA_BUILD_STAMP-->"
    idx = html.rindex("</body>")
    html = html[:idx] + stamp_at + "\n" + "\n".join(parts) + "\n" + html[idx:]
    html = add_season2(html)
    # a content stamp (not a time or git hash, so the same source always builds the same page):
    # the playtest log records which build a session came from; it covers every layer, Season 2 included
    import hashlib
    stamp = hashlib.sha1(html.replace(stamp_at, "").encode("utf-8")).hexdigest()[:10]
    html = html.replace(stamp_at, f"<script>window.NACECA_BUILD = {{ src:'{stamp}' }};</script>", 1)
    with open(HTML_OUT, "w", encoding="utf-8") as f:
        f.write(html)
    print(f"  built:  {HTML_OUT}  ({len(html):,} chars)")

# Season 2 ("Operation Upstream", src/season2 + art/season2): the LAST layer, after the beta and tactics.
# tools/season2_inject.py puts its seven scenes into ART_INLINE and appends its stylesheets and scripts.
# Delete src/season2 (and art/season2), or build with NACECA_SEASON2=0, and the page is Season 1 only.
def add_season2(html):
    if os.environ.get("NACECA_SEASON2") == "0" or not os.path.isdir(os.path.join(SRC, "season2")):
        print("  · season2 not present (or NACECA_SEASON2=0), skipped")
        return html
    import sys
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    from season2_inject import inject
    html, scenes = inject(html, ROOT)
    print(f"  season2: layer + {len(scenes)} scenes ({', '.join(scenes)})")
    return html

def main():
    bundle = build_bundle()
    build_html(bundle)
    # Mirror the assets/music directory next to naceca.html so the single-folder
    # delivery works: drop naceca.html + assets/ on a static host and music plays.
    import shutil
    src_music = os.path.join(SRC, "assets", "music")
    if os.path.exists(src_music) and not OUT_DIR:
        dst_music = os.path.join(ROOT, "assets", "music")
        os.makedirs(os.path.dirname(dst_music), exist_ok=True)
        if os.path.exists(dst_music):
            shutil.rmtree(dst_music)
        shutil.copytree(src_music, dst_music)
        total = sum(os.path.getsize(os.path.join(dst_music, f)) for f in os.listdir(dst_music))
        print(f"  music:  {dst_music}  ({total/1024/1024:.1f}MB)")
    # Syntax check the bundle
    rc = os.system(f"node --check {BUNDLE_OUT} 2>&1")
    if rc == 0:
        print("\n  ✓ bundle parses cleanly")
    else:
        print(f"\n  ✗ bundle has syntax errors (exit {rc})")
        raise SystemExit(rc)

if __name__ == "__main__":
    main()
