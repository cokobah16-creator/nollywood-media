if OUT_DIR:
    os.makedirs(OUT_DIR, exist_ok=True)
    BUNDLE_OUT = os.path.join(OUT_DIR, "_bundle.js")
    HTML_OUT = os.path.join(OUT_DIR, "naceca.html")

